#!/usr/bin/env node
/**
 * Generates backend/src/db/02-seed.sql from backend/src/data/*.json (which is
 * itself generated from frontend/public/assets/js/data.js by sync-seed-data.js).
 *
 * Chain: data.js  --sync-seed-data.js-->  *.json  --this script-->  02-seed.sql
 *
 * The frontend's content model is flat and pre-relational (text ids, no user
 * accounts, no auth) — backend/src/db/01-schema.sql is a normalized,
 * UUID-keyed, auth-aware schema. This script is the adapter between the two:
 * every old text id becomes a deterministic UUID (sha1-derived, so re-running
 * this script against unchanged JSON always produces the same ids — no drift
 * across regenerations), and each pandit gets a synthesized `users` row since
 * the old data has no account behind a pandit profile.
 *
 * 02-seed.sql is a plain SQL file so Postgres's docker-entrypoint-initdb.d
 * can run it directly (no Node runtime inside that container). It's checked
 * in and regenerated by `npm run seed` — tools/validate.js's seed-drift check
 * fails the build if someone edits data.js/*.json without regenerating it.
 *
 * Run: node backend/scripts/generate-seed-sql.js
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const bcrypt = require('bcryptjs');

const DATA_DIR = path.join(__dirname, '..', 'src', 'data');
const OUT_FILE = path.join(__dirname, '..', 'src', 'db', '02-seed.sql');

const load = (f) => JSON.parse(fs.readFileSync(path.join(DATA_DIR, f), 'utf8'));

// ---------------------------------------------------------------- helpers
function esc(v) {
  if (v === null || v === undefined) return 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
}
function arr(list) {
  if (!list || !list.length) return "'{}'";
  return `ARRAY[${list.map(esc).join(', ')}]`;
}
function jsonb(obj) {
  return `${esc(JSON.stringify(obj))}::jsonb`;
}
function bool(v) { return v ? 'TRUE' : 'FALSE'; }
function num(v) { return v === null || v === undefined ? 'NULL' : v; }
function slugify(s) {
  return String(s).toLowerCase().trim().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
}

// Deterministic, format-valid UUID from any string — stable across reruns so
// foreign keys don't shift every time this script regenerates the file.
// (Not a real RFC 4122 v5 UUID — just sha1(name) reshaped to look like one —
// which is fine here: these ids only need to be stable and unique, never
// cryptographically unguessable.)
function uid(name) {
  const hash = crypto.createHash('sha1').update(`panditconnect:${name}`).digest();
  const b = Buffer.from(hash.subarray(0, 16));
  b[6] = (b[6] & 0x0f) | 0x50; // version 5
  b[8] = (b[8] & 0x3f) | 0x80; // variant
  const h = b.toString('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}

// All synthetic seed accounts share one placeholder password so a future
// login UI can demo against them: "PanditConnect@2026". Real users created
// through POST /api/auth/register get their own bcrypt hash as normal.
const SEED_PASSWORD_HASH = bcrypt.hashSync('PanditConnect@2026', 10);

const services = load('services.json');
const temples = load('temples.json');
const pandits = load('pandits.json');
const reviews = load('reviews.json');
const posts = load('posts.json');
const plans = load('plans.json');
const faqs = load('faqs.json');
const stats = load('stats.json');
const taxonomy = load('taxonomy.json');
const recommendRules = load('recommend-rules.json');

const lines = [];
const say = (s) => lines.push(s);

say('-- GENERATED FILE — do not edit by hand.');
say('-- Source: backend/src/data/*.json, via backend/scripts/generate-seed-sql.js');
say(`-- Content hash: ${crypto.createHash('sha1').update(JSON.stringify({ services, temples, pandits, reviews, posts, plans, faqs, stats, taxonomy, recommendRules })).digest('hex')}`);
say('');

// ---------------------------------------------------------- system users
const ADMIN_USER_ID = uid('user:system-admin');
say('-- system/editorial user (blog authorship)');
say(`INSERT INTO users (id, email, phone, password_hash, full_name, role, status, email_verified, phone_verified)
     VALUES (${esc(ADMIN_USER_ID)}, ${esc('admin@panditconnect.demo')}, NULL, ${esc(SEED_PASSWORD_HASH)}, ${esc('PanditConnect Editorial')}, 'admin', 'active', TRUE, FALSE);`);
say('');

// ---------------------------------------------------- service categories
const categoryIdByName = new Map();
[...new Set(services.map((s) => s.cat))].forEach((cat) => {
  categoryIdByName.set(cat, uid(`service-category:${cat}`));
});
say('-- service_categories (derived from distinct services[].cat)');
[...categoryIdByName.entries()].forEach(([cat, id], i) => {
  say(`INSERT INTO service_categories (id, name, slug, display_order) VALUES (${esc(id)}, ${esc(cat)}, ${esc(slugify(cat))}, ${i});`);
});
say('');

// -------------------------------------------------------------- services
const serviceIdBySlug = new Map(); // old id (== new slug) -> new uuid
services.forEach((s) => { serviceIdBySlug.set(s.id, uid(`service:${s.id}`)); });

say('-- services (slug preserves the old id, so /api/services/:id URLs are unchanged)');
services.forEach((s) => {
  const id = serviceIdBySlug.get(s.id);
  const categoryId = categoryIdByName.get(s.cat);
  say(`INSERT INTO services (id, category_id, name, slug, description, short_description, icon_name, estimated_duration, samagri_list, is_active)
       VALUES (${esc(id)}, ${esc(categoryId)}, ${esc(s.name)}, ${esc(s.id)}, ${esc(s.desc)}, ${esc(s.desc.length > 480 ? s.desc.slice(0, 477) + '...' : s.desc)}, ${esc(s.icon)}, ${esc(s.dur)}, ${jsonb(s.samagri || [])}, TRUE);`);
});
say('');

say('-- service_samagri (one row per samagri item)');
services.forEach((s) => {
  const serviceId = serviceIdBySlug.get(s.id);
  (s.samagri || []).forEach((item, i) => {
    say(`INSERT INTO service_samagri (service_id, item_name, display_order) VALUES (${esc(serviceId)}, ${esc(item)}, ${i});`);
  });
});
say('');

// --------------------------------------------------------------- temples
const templeIdBySlug = new Map();
temples.forEach((t) => { templeIdBySlug.set(t.id, uid(`temple:${t.id}`)); });

say('-- temples');
temples.forEach((t) => {
  const id = templeIdBySlug.get(t.id);
  const history = `${t.about}\n\nTraditional timings: ${t.timings}\nEstablished: ${t.est}`;
  say(`INSERT INTO temples (
         id, name, slug, description, short_description, primary_deity, address_line1, city, state,
         latitude, longitude, cover_image_url, history, significance, avg_rating, review_count, pandit_count,
         is_verified, is_active
       ) VALUES (
         ${esc(id)}, ${esc(t.name)}, ${esc(t.id)}, ${esc(t.about)}, ${esc(t.about.length > 480 ? t.about.slice(0, 477) + '...' : t.about)},
         ${esc(t.deity)}, ${esc(t.city)}, ${esc(t.city)}, ${esc(t.state)}, ${num(t.lat)}, ${num(t.lng)}, ${esc(t.img)},
         ${esc(history)}, ${esc(t.highlights.join(' · '))},
         ${num(t.rating)}, ${num(t.reviews)}, ${num(t.pandits)}, TRUE, TRUE
       );`);
});
say('');

say('-- temple_services');
temples.forEach((t) => {
  const templeId = templeIdBySlug.get(t.id);
  t.services.forEach((sid) => {
    const serviceId = serviceIdBySlug.get(sid);
    if (!serviceId) return;
    say(`INSERT INTO temple_services (temple_id, service_id) VALUES (${esc(templeId)}, ${esc(serviceId)});`);
  });
});
say('');

// --------------------------------------------------------------- pandits
const panditIdBySlug = new Map();  // old id -> pandits.id
const panditUserIdBySlug = new Map(); // old id -> users.id
const panditServicesById = new Map(); // old id -> [service names], for review matching

say('-- one users row per pandit (synthetic account behind each demo profile)');
pandits.forEach((p) => {
  const userId = uid(`user:pandit:${p.id}`);
  panditUserIdBySlug.set(p.id, userId);
  say(`INSERT INTO users (id, email, phone, password_hash, full_name, role, status, city, state, email_verified, phone_verified)
       VALUES (${esc(userId)}, ${esc(`${p.id}@panditconnect.demo`)}, ${esc(p.phone)}, ${esc(SEED_PASSWORD_HASH)}, ${esc(p.name)}, 'pandit', 'active', ${esc(p.city)}, ${esc(p.state)}, TRUE, TRUE);`);
});
say('');

say('-- pandits');
pandits.forEach((p) => {
  const id = uid(`pandit:${p.id}`);
  panditIdBySlug.set(p.id, id);
  const userId = panditUserIdBySlug.get(p.id);
  const bio = `${p.about}\n\nGotra: ${p.gotra} | Education: ${p.edu}`;
  const specNames = p.services.map((sid) => services.find((s) => s.id === sid)?.name).filter(Boolean);
  panditServicesById.set(p.id, specNames);
  const verification = p.verified ? 'verified' : 'unverified';
  const tier = p.tier.toLowerCase();
  say(`INSERT INTO pandits (
         id, user_id, bio, short_bio, experience_years, specializations, public_phone, whatsapp_number,
         profile_photo_url, verification_status, review_count, avg_rating, current_tier, slug, is_available
       ) VALUES (
         ${esc(id)}, ${esc(userId)}, ${esc(bio)}, ${esc(p.about.length > 280 ? p.about.slice(0, 277) + '...' : p.about)},
         ${num(p.exp)}, ${arr(specNames)}, ${esc(p.phone)}, ${esc(p.phone)}, ${esc(p.img)},
         '${verification}', ${num(p.reviews)}, ${num(p.rating)}, '${tier}', ${esc(p.id)}, TRUE
       );`);
});
say('');

say('-- pandit_languages / pandit_services / pandit_temples / pandit_certificates');
pandits.forEach((p) => {
  const panditId = panditIdBySlug.get(p.id);
  p.langs.forEach((l) => say(`INSERT INTO pandit_languages (pandit_id, language) VALUES (${esc(panditId)}, ${esc(l)});`));
  p.services.forEach((sid) => {
    const serviceId = serviceIdBySlug.get(sid);
    if (serviceId) say(`INSERT INTO pandit_services (pandit_id, service_id) VALUES (${esc(panditId)}, ${esc(serviceId)});`);
  });
  p.temples.forEach((tid, i) => {
    const templeId = templeIdBySlug.get(tid);
    if (templeId) say(`INSERT INTO pandit_temples (pandit_id, temple_id, is_primary) VALUES (${esc(panditId)}, ${esc(templeId)}, ${bool(i === 0)});`);
  });
  say(`INSERT INTO pandit_certificates (pandit_id, certificate_name, is_verified) VALUES (${esc(panditId)}, ${esc(p.edu)}, ${bool(p.verified)});`);
});
say('');

// --------------------------------------------------------- subscription plans
say('-- subscription_plans');
plans.forEach((p, i) => {
  const priceDigits = (p.price.match(/\d+/g) || ['0']).join('');
  say(`INSERT INTO subscription_plans (name, tier, price_monthly, features, is_popular, display_order)
       VALUES (${esc(p.name)}, '${p.name.toLowerCase()}', ${priceDigits}, ${jsonb({ highlights: p.feats, cta: p.cta, per: p.per })}, ${bool(!!p.popular)}, ${i});`);
});
say('');

// --------------------------------------------------------------- reviews
say('-- reviews (site testimonials, best-effort matched to a pandit offering that service)');
reviews.forEach((r, i) => {
  const reviewerId = uid(`user:reviewer:${i}`);
  say(`INSERT INTO users (id, email, full_name, role, status, city, password_hash, email_verified)
       VALUES (${esc(reviewerId)}, ${esc(`reviewer-${i}@panditconnect.demo`)}, ${esc(r.name)}, 'devotee', 'active', ${esc(r.city)}, ${esc(SEED_PASSWORD_HASH)}, TRUE);`);

  const svcLower = r.service.toLowerCase();
  let matchId = null;
  for (const p of pandits) {
    const names = panditServicesById.get(p.id) || [];
    if (names.some((n) => n.toLowerCase() === svcLower) && p.city === r.city) { matchId = p.id; break; }
  }
  if (!matchId) {
    for (const p of pandits) {
      const names = panditServicesById.get(p.id) || [];
      if (names.some((n) => n.toLowerCase() === svcLower)) { matchId = p.id; break; }
    }
  }
  if (!matchId) matchId = pandits[i % pandits.length].id;
  const panditId = panditIdBySlug.get(matchId);
  const svcId = services.find((s) => s.name.toLowerCase() === svcLower);

  say(`INSERT INTO reviews (user_id, reviewable_type, reviewable_id, rating, body, service_id, is_approved)
       VALUES (${esc(reviewerId)}, 'pandit', ${esc(panditId)}, ${num(r.rating)}, ${esc(r.text)}, ${svcId ? esc(serviceIdBySlug.get(svcId.id)) : 'NULL'}, TRUE);`);
});
say('');

// ------------------------------------------------------------- blog_posts
say('-- blog_posts');
posts.forEach((p) => {
  const publishedAt = new Date(p.date);
  const iso = Number.isNaN(publishedAt.getTime()) ? null : publishedAt.toISOString();
  say(`INSERT INTO blog_posts (author_id, title, slug, excerpt, body, category, status, published_at)
       VALUES (${esc(ADMIN_USER_ID)}, ${esc(p.title)}, ${esc(p.id)}, ${esc(p.excerpt)}, ${esc(p.excerpt)}, ${esc(p.cat)}, 'published', ${iso ? esc(iso) : 'NOW()'});`);
});
say('');

// ---------------------------------------------------- app-specific tables
say('-- faqs');
faqs.forEach((f, i) => {
  say(`INSERT INTO faqs (question, answer, display_order) VALUES (${esc(f.q)}, ${esc(f.a)}, ${i});`);
});
say('');

say('-- stats');
stats.forEach((s, i) => {
  say(`INSERT INTO stats (icon, number_label, label, display_order) VALUES (${esc(s.icon)}, ${esc(s.num)}, ${esc(s.label)}, ${i});`);
});
say('');

say('-- taxonomy');
['cities', 'states', 'languages'].forEach((key) => {
  const kind = { cities: 'city', states: 'state', languages: 'language' }[key];
  taxonomy[key].forEach((value, i) => say(`INSERT INTO taxonomy (kind, value, display_order) VALUES (${esc(kind)}, ${esc(value)}, ${i});`));
});
say('');

say('-- recommend_rules');
recommendRules.forEach((r) => {
  say(`INSERT INTO recommend_rules (keywords, service_slugs, why) VALUES (${arr(r.keys)}, ${arr(r.svc)}, ${esc(r.why)});`);
});
say('');

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, lines.join('\n') + '\n');
console.log(`wrote ${OUT_FILE.replace(path.join(__dirname, '..', '..'), '.')} (${lines.filter((l) => l.startsWith('INSERT')).length} statements)`);
